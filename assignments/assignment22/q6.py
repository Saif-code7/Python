# **6.Take input of marks of 3 subjects and calculate the average marks.**

# **Input:** 70, 80, 90

# **Output:** 80.0

n1 = float(input("enter marks of first subject  :  "))
n2 = float(input("enter marks of second subject  :  "))
n3 = float(input("enter marks of third subject  :  "))

avg = (n1+n2+n3)/3
print(f"the average would be : {avg}")